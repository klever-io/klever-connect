import { ValidationError } from '@klever/connect-core'
import {
  bech32Decode,
  hexDecode,
  TransferContract,
  FreezeContract,
  UnfreezeContract,
  DelegateContract,
  UndelegateContract,
  WithdrawContract,
  ClaimContract,
  VoteContract,
  SmartContract,
  ClaimType,
  ContractType,
  type ITXContract,
} from '@klever/connect-encoding'
import type { AmountLike, ContractRequestData } from '@klever/connect-provider'

/**
 * Encodes builder contract requests into `TXContract` messages offline, the way
 * the node's `/transaction/send` does (klever-go `data/transaction/transaction.go`,
 * the `add<Contract>` functions). The node signs and hashes these bytes as given,
 * so each field follows klever-go's `contracts.proto` and conversion rules.
 *
 * Fields with their default value (0, empty) are left out, as Go's proto3
 * encoding does: protobuf.js writes any field that is set, even to 0.
 */

/** Type URL prefix `anypb.New` uses in klever-go. */
const TYPE_URL_PREFIX = 'type.googleapis.com/proto.'

const encoder = new TextEncoder()

/** A message class generated by protobuf.js. */
interface MessageClass {
  encode(message: object): { finish(): Uint8Array }
}

/**
 * The contract types `buildProto()` can encode. The others need data the node
 * fills in from chain state, or are not covered yet: build them with `build()`.
 */
export const OFFLINE_CONTRACT_TYPES: readonly number[] = [0, 4, 5, 6, 7, 8, 9, 14, 63]

/**
 * Encode one contract request into a `TXContract` (`Type` and an `Any` parameter).
 *
 * Royalties: for a KDA with royalties, the node looks up `kdaRoyalties` and
 * `klvRoyalties` on chain when it builds a transfer or a smart-contract call value.
 * Offline there is no chain, so a transfer carries only the royalties passed in
 * the request, and a call value carries none: a call value in an asset with
 * transfer royalties fails on chain (klever-go rejects the royalty mismatch).
 *
 * @throws {ValidationError} If the contract type is not supported offline, or a
 *   field cannot be encoded
 */
export function encodeContract(contract: ContractRequestData): ITXContract {
  const type = contract.contractType
  const c = contract as unknown as { [k: string]: unknown }

  switch (type) {
    case 0: // Transfer: addTransfer
      return pack(type, TransferContract, {
        ToAddress: address(c['receiver'], 'receiver'),
        AssetID: text(c['kda'], 'kda'),
        Amount: int64(c['amount'], 'amount'),
        KDARoyalties: int64(c['kdaRoyalties'], 'kdaRoyalties'),
        KLVRoyalties: int64(c['klvRoyalties'], 'klvRoyalties'),
      })
    case 4: // Freeze: addFreeze
      return pack(type, FreezeContract, {
        AssetID: text(c['kda'], 'kda'),
        Amount: int64(c['amount'], 'amount'),
      })
    case 5: // Unfreeze: addUnfreeze takes hex, or else the raw bytes
      return pack(type, UnfreezeContract, {
        AssetID: text(c['kda'], 'kda'),
        BucketID: hexOrText(required(c['bucketId'], 'bucketId'), 'bucketId'),
      })
    case 6: // Delegate: addDelegate
      return pack(type, DelegateContract, {
        ToAddress: address(c['receiver'], 'receiver'),
        BucketID: hex(required(c['bucketId'], 'bucketId'), 'bucketId'),
      })
    case 7: // Undelegate: addUndelegate
      return pack(type, UndelegateContract, {
        BucketID: hex(required(c['bucketId'], 'bucketId'), 'bucketId'),
      })
    case 8: // Withdraw: addWithdraw
      return pack(type, WithdrawContract, {
        AssetID: text(c['kda'], 'kda'),
        WithdrawType: int32(c['withdrawType'], 'withdrawType'),
        // lowercase in klever-go's proto (`int64 amount = 3`)
        amount: int64(c['amount'], 'amount'),
        CurrencyID: text(c['currencyID'], 'currencyID'),
      })
    case 9: {
      // Claim: addClaim hex-decodes the ID of a market claim only
      const claimType = int32(c['claimType'], 'claimType')
      const id = c['id']
      return pack(type, ClaimContract, {
        ClaimType: claimType,
        ID: claimType === ClaimType.MarketClaim ? hex(id, 'id') : text(id, 'id'),
      })
    }
    case 14: // Vote: addVote
      return pack(type, VoteContract, {
        ProposalID: int64(c['proposalId'], 'proposalId'),
        Amount: int64(c['amount'], 'amount'),
        Type: int32(c['type'], 'type'),
      })
    case 63: {
      // SmartContract: addSmartContract
      const scType = int32(c['scType'], 'scType')
      // klever-go's SCType has only SCInvoke (0) and SCDeploy (1); the node
      // rejects anything else with "invalid smart contract type".
      if (scType !== undefined && scType !== 0 && scType !== 1) {
        throw new ValidationError(
          `Smart contract type ${String(scType)} is not supported by the node; use 0 (invoke) or 1 (deploy)`,
          { scType },
        )
      }
      return pack(type, SmartContract, {
        Type: scType,
        Address: c['address'] === undefined ? undefined : address(c['address'], 'address'),
        CallValue: callValue(c['callValue']),
      })
    }
    default:
      throw new ValidationError(
        `Contract type ${String(type)} cannot be built offline yet; use build() instead`,
        { contractType: type },
      )
  }
}

/** Wrap an encoded contract in a `TXContract` with the type URL klever-go checks. */
function pack(type: number, cls: MessageClass, fields: { [k: string]: unknown }): ITXContract {
  // Every caller passes a ContractType member from the encodeContract switch
  const name = ContractType[type] as string
  const value = cls.encode(withoutDefaults(fields)).finish()
  const txContract: ITXContract = {
    Parameter: {
      // TransferContractType -> proto.TransferContract (klever-go getCanonicalName)
      type_url: TYPE_URL_PREFIX + name.replace(/Type$/, ''),
      // Go leaves out empty bytes; protobuf.js would write an empty field
      // and change the hash (e.g. a staking claim with no ID).
      ...(value.length > 0 ? { value } : {}),
    },
  }
  if (type !== 0) txContract.Type = type
  return txContract
}

/**
 * Drop the fields proto3 would not write: undefined, null, 0, empty bytes or
 * strings, and empty objects or arrays. Used for contract messages and for
 * RawData, whose signed bytes must match the node's Go encoding.
 */
export function withoutDefaults<T extends object>(
  fields: T,
): { [K in keyof T]?: Exclude<T[K], undefined> } {
  const out: { [k: string]: unknown } = {}
  for (const [key, value] of Object.entries(fields)) {
    if (value === undefined || value === null || value === 0 || value === '') continue
    if (value instanceof Uint8Array && value.length === 0) continue
    if (typeof value === 'object' && !(value instanceof Uint8Array)) {
      if (Object.keys(value).length === 0) continue
    }
    out[key] = value
  }
  return out as { [K in keyof T]?: Exclude<T[K], undefined> }
}

/** A required request field. */
function required(value: unknown, field: string): unknown {
  if (value === undefined || value === null || value === '') {
    throw new ValidationError(`${field} is required`)
  }
  return value
}

/**
 * A non-negative int64 that fits a JS number exactly (the proto classes use
 * numbers, not Long). Rejects anything that would change in conversion.
 */
function int64(value: unknown, field: string): number | undefined {
  if (value === undefined || value === null) return undefined
  let n: number
  // A bigint outside the safe range converts to an unsafe number, which the
  // check below rejects
  if (typeof value === 'bigint') {
    n = Number(value)
  } else if (typeof value === 'number') {
    n = value
  } else if (typeof value === 'string' && /^[0-9]+$/.test(value)) {
    n = Number(value)
  } else {
    throw new ValidationError(`${field} must be a non-negative safe integer`)
  }
  if (!Number.isSafeInteger(n) || n < 0) {
    throw new ValidationError(`${field} must be a non-negative safe integer`)
  }
  return n
}

/** An enum or int32 field. */
function int32(value: unknown, field: string): number | undefined {
  const n = int64(value, field)
  if (n !== undefined && n > 0x7fffffff) {
    throw new ValidationError(`${field} is out of range`)
  }
  return n
}

/** A string sent as its UTF-8 bytes (asset IDs, as `[]byte(request.KDA)` in Go). */
function text(value: unknown, field: string): Uint8Array | undefined {
  if (value === undefined || value === null) return undefined
  if (typeof value !== 'string') {
    throw new ValidationError(`${field} must be a string`)
  }
  return encoder.encode(value)
}

/** A hex string decoded to bytes (`hex.DecodeString` in Go). */
function hex(value: unknown, field: string): Uint8Array | undefined {
  if (value === undefined || value === null || value === '') return undefined
  if (typeof value !== 'string' || !isHex(value)) {
    throw new ValidationError(`${field} must be a hex string`)
  }
  return hexDecode(value)
}

/** Hex decoded when it is valid hex, else the string's bytes, as addUnfreeze does. */
function hexOrText(value: unknown, field: string): Uint8Array | undefined {
  if (typeof value === 'string' && isHex(value)) return hexDecode(value)
  return text(value, field)
}

/** Hex as Go's `hex.DecodeString` accepts it: even length, no prefix. */
function isHex(value: string): boolean {
  return value.length % 2 === 0 && /^[0-9a-fA-F]*$/.test(value)
}

/** A bech32 address decoded to its 32 public key bytes. */
function address(value: unknown, field: string): Uint8Array {
  if (typeof value !== 'string' || value === '') {
    throw new ValidationError(`${field} must be a bech32 address`)
  }
  try {
    return bech32Decode(value).data
  } catch {
    throw new ValidationError(`${field} must be a bech32 address`)
  }
}

/**
 * The smart contract call value: a `map<string, CallValue>` keyed by asset ID.
 * Keys are sorted so the same call value always encodes to the same bytes.
 */
function callValue(value: unknown): { [k: string]: { Amount?: number } } | undefined {
  if (value === undefined || value === null) return undefined
  if (typeof value !== 'object' || Array.isArray(value)) {
    throw new ValidationError('callValue must map asset IDs to amounts')
  }
  const entries = Object.entries(value as Record<string, AmountLike>).sort(([a], [b]) =>
    a < b ? -1 : a > b ? 1 : 0,
  )
  const out: { [k: string]: { Amount?: number } } = {}
  for (const [assetId, amount] of entries) {
    out[assetId] = withoutDefaults({ Amount: int64(amount, `callValue.${assetId}`) })
  }
  return out
}
